/** Real concurrent connections; cleanup deletes only the fixture IDs created below. */
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../apps/api/package.json',import.meta.url));
require('reflect-metadata');
const {Pool}=require('pg');
const {createConnection}=await import('../apps/api/dist/postgres/connection.js');
const {SqlRecords}=await import('../apps/api/dist/postgres/records.js');
const {DomainOutboxService}=await import('../apps/api/dist/common/events/domain-outbox.service.js');
const {PublicationService}=await import('../apps/api/dist/modules/publication/publication.service.js');
const {AttemptsService}=await import('../apps/api/dist/modules/assessment/attempts/attempts.service.js');
assert.equal(process.env.SERVICE_ROLE,'assessment');
const pool=new Pool({max:6,connectionString:process.env.F01_ASSESSMENT_TEST_DATABASE_URL}),exams=new SqlRecords(createConnection(pool),'exams'),questions=new SqlRecords(createConnection(pool),'questions');
const connection=createConnection(pool);
const service=new AttemptsService(connection,undefined,new DomainOutboxService(connection));
const examId=randomUUID(),userId=randomUUID(),questionIds=[randomUUID(),randomUUID()],attemptIds=[];
try {
  await exams.insert({_id:examId,name:`concurrency-${examId}`,slug:`concurrency-${examId}`,type:'TOEIC',isActive:true});
  for(const id of questionIds)await questions.insert({_id:id,examId,section:'READING',part:5,content:`Concurrent fixture ${id}`,options:[{key:'A',text:'First'},{key:'B',text:'Second'},{key:'C',text:'Third'},{key:'D',text:'Fourth'}],correctAnswer:'A',isActive:true});
  const publication=new PublicationService(connection),actor=randomUUID();
  await publication.validate('exams',examId,actor,'en');
  await publication.publish('exams',examId,actor,'en');
  const fresh=async(mode='TEST')=>{const created=await service.create(userId,{examId,mode,selectedParts:[5]});attemptIds.push(created._id);return created._id;};
  const id=await fresh();
  await Promise.all(questionIds.map(questionId=>service.saveAnswer(userId,id,{questionId,answer:'A'})));
  assert.equal(Object.keys((await service.findOne(userId,id)).answers).length,2,'Concurrent answers must both persist');
  const submitted=await service.submit(userId,id);
  assert.equal(submitted.correctAnswers,2);
  const duplicateId=await fresh();
  const duplicates=await Promise.allSettled(['A','B'].map(answer=>service.saveAnswer(userId,duplicateId,{questionId:questionIds[0],answer})));
  assert.equal(duplicates.filter(result=>result.status==='fulfilled').length,2,'TEST answers remain editable before submission');
  assert.ok(['A','B'].includes((await service.findOne(userId,duplicateId)).answers[questionIds[0]]));
  const practiceId=await fresh('PRACTICE');
  await service.saveAnswer(userId,practiceId,{questionId:questionIds[0],answer:'A'});
  await service.checkAnswer(userId,practiceId,questionIds[0]);
  const locked=await Promise.allSettled(['B','C'].map(answer=>service.saveAnswer(userId,practiceId,{questionId:questionIds[0],answer})));
  assert.ok(locked.every(result=>result.status==='rejected'&&/already been answered/.test(result.reason.message)),'Revealed PRACTICE answers must stay locked');
  const raceId=await fresh();
  await Promise.allSettled([service.saveAnswer(userId,raceId,{questionId:questionIds[0],answer:'A'}),service.submit(userId,raceId)]);
  const final=await service.findOne(userId,raceId);
  assert.equal(final.status,'FINISHED');
  assert.equal(final.correctAnswers,Object.keys(final.answers).length,'Grading must include exactly the answers that won before submission');
  console.log('PostgreSQL concurrency: answers preserved, TEST edits allowed, revealed PRACTICE answers locked, submission race consistent');
} finally {
  await pool.query('DELETE FROM public.outbox_events WHERE aggregate_id=$1',[userId]);
  await pool.query('DELETE FROM public.content_publication_audit WHERE resource_id=$1',[examId]);
  await pool.query('DELETE FROM attempts WHERE id=ANY($1::uuid[])',[attemptIds]);
  await pool.query('DELETE FROM questions WHERE id=ANY($1::uuid[])',[questionIds]);
  await pool.query('DELETE FROM exams WHERE id=$1',[examId]);
  await pool.end();
}
