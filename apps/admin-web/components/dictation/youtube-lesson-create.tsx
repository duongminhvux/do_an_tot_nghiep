"use client";
import { useState, useRef } from "react";
import { useQuery } from "@tanstack/react-query";
import { useParams, useRouter } from "next/navigation";
import {
  YoutubePlayer,
  type YoutubePlayerHandle,
} from "@repo/ui/youtube-player";
import { dictationService } from "@/services/dictation.service";
import type { DictationTopic, DictationLevel } from "@/types/dictation";
type Segment = { order: number; text: string; startMs: number; endMs: number };
const field =
  "mt-1 w-full rounded-lg border border-slate-300 bg-white p-2 text-sm";
export function YoutubeLessonCreate({ onBack }: { onBack: () => void }) {
  const { locale } = useParams<{ locale: string }>(),
    router = useRouter();
  const playerRef = useRef<YoutubePlayerHandle>(null);
  const [url, setUrl] = useState(""),
    [title, setTitle] = useState(""),
    [description, setDescription] = useState(""),
    [topicId, setTopicId] = useState(""),
    [sectionId, setSectionId] = useState(""),
    [level, setLevel] = useState<DictationLevel>("B1");
  const [start, setStart] = useState(0),
    [end, setEnd] = useState(""),
    [subtitleText, setSubtitleText] = useState(""),
    [segments, setSegments] = useState<Segment[]>([]),
    [videoId, setVideoId] = useState(""),
    [loadedUrl, setLoadedUrl] = useState("");
  const [busy, setBusy] = useState(false),
    [error, setError] = useState(""),
    [reviewed, setReviewed] = useState(false),
    [automatic, setAutomatic] = useState(false);
  const { data } = useQuery({
    queryKey: ["dictation-hierarchy"],
    queryFn: () => dictationService.getHierarchy(),
  });
  const topics = (data?.data || []) as DictationTopic[];
  const sections = topics.find((t) => t._id === topicId)?.sections || [];
  const invalidate = () => {
    setSegments([]);
    setVideoId("");
    setLoadedUrl("");
    setReviewed(false);
  };
  async function preview() {
    setBusy(true);
    setError("");
    try {
      const result = (
        await dictationService.previewYoutube({
          url,
          subtitleText,
          startSeconds: start,
          ...(end ? { endSeconds: Number(end) } : {}),
        })
      ).data;
      setSegments(result.segments);
      setVideoId(result.videoId);
      setLoadedUrl(result.youtubeUrl);
      setAutomatic(result.autoGenerated);
      setReviewed(false);
      if (!title) setTitle(`YouTube · ${result.videoId}`);
    } catch (e: any) {
      setError(e.response?.data?.message || e.message);
    } finally {
      setBusy(false);
    }
  }
  async function create() {
    setBusy(true);
    setError("");
    try {
      const result = await dictationService.createYoutube({
        title,
        description,
        topicId,
        sectionId,
        level,
        language: "en-US",
        voiceIds: ["af_heart"],
        speed: 1,
        pauseAfterMs: 0,
        youtubeUrl: loadedUrl,
        segments: segments.map((s, order) => ({ ...s, order })),
      });
      router.push(`/${locale}/dictation/${result.data._id}`);
    } catch (e: any) {
      setError(e.response?.data?.message || e.message);
    } finally {
      setBusy(false);
    }
  }
  return (
    <div className="mx-auto max-w-5xl space-y-5 p-6">
      <button
        onClick={onBack}
        className="text-sm text-blue-700"
        disabled={busy}
      >
        ← Chọn nguồn bài nghe
      </button>
      <h1 className="text-2xl font-bold">Tạo bài nghe từ YouTube</h1>
      <p className="text-sm text-slate-600">
        Dán link video → lấy phụ đề tiếng Anh → kiểm tra từng câu → lưu đề nháp.
        Học viên nghe từng đoạn và nhập câu trả lời để chấm điểm.
      </p>
      {error && (
        <p role="alert" className="rounded-lg bg-red-50 p-3 text-red-700">
          {Array.isArray(error) ? error.join(", ") : error}
        </p>
      )}
      <section className="space-y-4 rounded-xl border bg-white p-5">
        <label className="block text-sm">
          Link YouTube
          <input
            className={field}
            disabled={busy}
            value={url}
            placeholder="https://www.youtube.com/watch?v=..."
            onChange={(e) => {
              setUrl(e.target.value);
              invalidate();
            }}
          />
        </label>
        <div className="grid gap-3 sm:grid-cols-2">
          <label className="text-sm">
            Từ giây
            <input
              className={field}
              type="number"
              min={0}
              max={7200}
              disabled={busy}
              value={start}
              onChange={(e) => {
                setStart(Number(e.target.value));
                invalidate();
              }}
            />
          </label>
          <label className="text-sm">
            Đến giây (để trống để lấy hết)
            <input
              className={field}
              type="number"
              min={1}
              max={7200}
              value={end}
              disabled={busy}
              onChange={(e) => {
                setEnd(e.target.value);
                invalidate();
              }}
            />
          </label>
        </div>
        <details className="text-sm">
          <summary>Tải phụ đề .srt/.vtt nếu không lấy được tự động</summary>
          <input
            className={field}
            type="file"
            disabled={busy}
            accept=".srt,.vtt"
            onChange={async (e) => {
              const file = e.target.files?.[0];
              if (!file) return;
              if (file.size > 500000) {
                setError("Phụ đề tối đa 500 KB.");
                return;
              }
              setSubtitleText(await file.text());
              invalidate();
            }}
          />
          <button
            type="button"
            onClick={() => {
              setSubtitleText("");
              invalidate();
            }}
            className="mt-2 text-blue-700"
          >
            Dùng phụ đề tự động từ YouTube
          </button>
          {subtitleText && <p>Đã chọn file phụ đề để nhập.</p>}
        </details>
        <button
          disabled={busy || !url.trim()}
          onClick={() => void preview()}
          className="rounded-lg bg-blue-600 px-4 py-2 text-white disabled:opacity-50"
        >
          {busy ? "Đang xử lý…" : "Lấy phụ đề & chia đoạn"}
        </button>
      </section>
      {!!segments.length && (
        <>
          <YoutubePlayer ref={playerRef} videoId={videoId} />
          <section className="grid gap-4 rounded-xl border bg-white p-5 sm:grid-cols-2">
            <label>
              Tiêu đề
              <input
                value={title}
                maxLength={160}
                onChange={(e) => setTitle(e.target.value)}
                className={field}
              />
            </label>
            <label>
              Độ khó
              <select
                className={field}
                value={level}
                onChange={(e) => setLevel(e.target.value as DictationLevel)}
              >
                {["A1", "A2", "B1", "B2", "C1", "C2"].map((l) => (
                  <option key={l}>{l}</option>
                ))}
              </select>
            </label>
            <label>
              Topic
              <select
                value={topicId}
                onChange={(e) => {
                  setTopicId(e.target.value);
                  setSectionId("");
                }}
                className={field}
              >
                <option value="">Chọn Topic…</option>
                {topics.map((t) => (
                  <option key={t._id} value={t._id}>
                    {t.title}
                  </option>
                ))}
              </select>
            </label>
            <label>
              Section
              <select
                className={field}
                value={sectionId}
                onChange={(e) => setSectionId(e.target.value)}
              >
                <option value="">Chọn Section…</option>
                {sections.map((s) => (
                  <option key={s._id} value={s._id}>
                    {s.title}
                  </option>
                ))}
              </select>
            </label>
            <label className="sm:col-span-2">
              Mô tả
              <textarea
                className={field}
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                maxLength={1000}
              />
            </label>
          </section>
          <section className="space-y-3 rounded-xl border bg-white p-5">
            <h2 className="font-bold">
              Kiểm tra {segments.length} đoạn phụ đề{" "}
              {automatic ? "(phụ đề tự động)" : ""}
            </h2>
            <p className="text-sm text-slate-600">
              Sửa phụ đề sai và mốc thời gian trước khi dùng làm đáp án. Mốc
              tính bằng giây trên video gốc.
            </p>
            <div className="max-h-[600px] space-y-4 overflow-auto">
              {segments.map((s, i) => (
                <div
                  key={i}
                  className="grid gap-2 rounded-lg border p-3 sm:grid-cols-[60px_100px_100px_1fr]"
                >
                  <button
                    type="button"
                    onClick={() => playerRef.current?.play(s.startMs, s.endMs)}
                    className="text-sm text-blue-700"
                  >
                    Nghe #{i + 1}
                  </button>
                  {(["startMs", "endMs"] as const).map((key) => (
                    <label key={key} className="text-xs">
                      {key === "startMs" ? "Bắt đầu" : "Kết thúc"}
                      <input
                        aria-label={`${key} đoạn ${i + 1}`}
                        type="number"
                        step="0.01"
                        min="0"
                        value={s[key] / 1000}
                        className={field}
                        onChange={(e) => {
                          setReviewed(false);
                          setSegments((old) =>
                            old.map((v, j) =>
                              j === i
                                ? {
                                    ...v,
                                    [key]: Math.round(
                                      Number(e.target.value) * 1000,
                                    ),
                                  }
                                : v,
                            ),
                          );
                        }}
                      />
                    </label>
                  ))}
                  <textarea
                    aria-label={`Phụ đề đoạn ${i + 1}`}
                    className={field}
                    value={s.text}
                    onChange={(e) => {
                      setReviewed(false);
                      setSegments((old) =>
                        old.map((v, j) =>
                          j === i ? { ...v, text: e.target.value } : v,
                        ),
                      );
                    }}
                  />
                  <button
                    className="text-xs text-red-700"
                    onClick={() => {
                      setReviewed(false);
                      setSegments((old) => old.filter((_, j) => j !== i));
                    }}
                  >
                    Xóa đoạn
                  </button>
                </div>
              ))}
            </div>
            <label className="flex gap-2 text-sm">
              <input
                type="checkbox"
                checked={reviewed}
                onChange={(e) => setReviewed(e.target.checked)}
              />{" "}
              Tôi đã đối chiếu phụ đề với video và kiểm tra mốc thời gian
            </label>
            <button
              disabled={
                busy || !reviewed || !title.trim() || !topicId || !sectionId
              }
              onClick={() => void create()}
              className="rounded-lg bg-blue-600 px-4 py-2 text-white disabled:opacity-50"
            >
              Lưu bài nháp để duyệt
            </button>
          </section>
        </>
      )}
    </div>
  );
}
