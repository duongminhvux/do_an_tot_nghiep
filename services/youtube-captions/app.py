import html
import re
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from requests import Session
from youtube_transcript_api import YouTubeTranscriptApi
from urllib.parse import urlsplit,urlunsplit,parse_qsl,urlencode
from sentence_split import sentence_segments,json3_cues

app=FastAPI(title='YouTube caption importer')

class Preview(BaseModel):
    videoId: str=Field(pattern=r'^[a-zA-Z0-9_-]{11}$')
    subtitleText: str=Field(default='',max_length=500000)
    startSeconds: float=Field(default=0,ge=0,le=7200)
    endSeconds: float|None=Field(default=None,gt=0,le=7200)

class TimedSession(Session):
    def request(self,*args,**kwargs):
        kwargs.setdefault('timeout',15)
        return super().request(*args,**kwargs)

def timestamp(text):
    pieces=text.replace(',','.').split(':')
    if len(pieces) not in (2,3):raise ValueError('Mốc thời gian không hợp lệ.')
    result=0
    for p in pieces:result=result*60+float(p)
    return result

def parse_subtitles(text):
    lines=text.replace('\r','').split('\n');cues=[]
    for index,line in enumerate(lines):
        match=re.match(r'^\s*((?:\d+:)?\d{2}:\d{2}[.,]\d{3})\s*-->\s*((?:\d+:)?\d{2}:\d{2}[.,]\d{3})',line)
        if not match:continue
        words=[]
        for value in lines[index+1:]:
            if not value.strip():break
            words.append(value)
        start,end=map(timestamp,match.groups())
        if end<=start:raise ValueError('Mốc kết thúc phải lớn hơn mốc bắt đầu.')
        cues.append({'text':' '.join(words),'start':start,'duration':end-start})
    if not cues:raise ValueError('Không tìm thấy phụ đề có mốc thời gian. Hãy dùng file .srt hoặc .vtt.')
    return cues

def segments(cues,start=0,end=None,restore=False):
    return sentence_segments(cues,start,end,restore=restore)

@app.get('/health')
def health():return {'ready':True}

@app.post('/preview')
def preview(body:Preview):
    if body.endSeconds is not None and body.endSeconds<=body.startSeconds:raise HTTPException(400,'Khoảng thời gian không hợp lệ.')
    try:
        generated=False;timing='subtitle_estimated'
        if body.subtitleText:
            cues=parse_subtitles(body.subtitleText);source='uploaded_subtitles';language='en'
        else:
            with TimedSession() as session:
                tracks=YouTubeTranscriptApi(http_client=session).list(body.videoId)
                try:track=tracks.find_manually_created_transcript(['en','en-US','en-GB'])
                except Exception:track=tracks.find_transcript(['en','en-US','en-GB'])
                generated=track.is_generated;language=track.language_code;source='youtube_captions'
                try:
                    url=urlsplit(track._url);query=dict(parse_qsl(url.query));query['fmt']='json3'
                    response=session.get(urlunsplit((url.scheme,url.netloc,url.path,urlencode(query),url.fragment)))
                    response.raise_for_status();raw=response.json();cues=json3_cues(raw)
                    if not cues:raise ValueError('No word cues')
                    if any('tOffsetMs' in segment for event in raw.get('events',[]) for segment in event.get('segs',[])):timing='youtube_word'
                except Exception:
                    cues=track.fetch().to_raw_data()
        word_count=sum(len(c['text'].split()) for c in cues)
        punctuation=sum(bool(re.search(r'''[.!?]["']?$''',c['text'].strip())) for c in cues)
        restore=generated or (word_count>20 and punctuation<max(1,word_count//100))
        return {'segmentationMethod':'local_sentences' if restore else 'punctuated_sentences','timingPrecision':timing,
                'videoId':body.videoId,'source':source,'language':language,'autoGenerated':generated,
                'segments':segments(cues,body.startSeconds,body.endSeconds,restore=restore)}
    except ValueError as exc:raise HTTPException(400,str(exc))
    except Exception as exc:
        code=type(exc).__name__
        raise HTTPException(422,{'code':code,'message':'Không lấy được phụ đề tiếng Anh từ YouTube. Video có thể không có phụ đề, bị hạn chế hoặc YouTube đang chặn yêu cầu. Bạn có thể tải phụ đề .srt/.vtt lên để tiếp tục.'})
